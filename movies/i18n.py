def get_lang(session: dict[str, Any]) -> str:
    """Return active language code e.g. 'PL', 'EN', 'DE', 'ES', 'FR', 'IT'."""
    return session.get("lang", "PL")


def set_lang(session: dict[str, Any], lang_code: str) -> str:
    code = lang_code.upper().strip()
    if code not in TRANSLATIONS:
        code = "PL"
    session["lang"] = code
    return code


def t(key: str, lang: str = "PL") -> str:
    """Translate key to specified language with universal fallback to EN for non-PL languages."""
    code = (lang or "PL").upper().strip()
    translations = TRANSLATIONS.get(code, {})
    if key in translations:
        return translations[key]

    if code != "PL":
        en_dict = TRANSLATIONS.get("EN", {})
        if key in en_dict:
            return en_dict[key]
        return key

    pl_dict = TRANSLATIONS.get("PL", {})
    return pl_dict.get(key, key)
