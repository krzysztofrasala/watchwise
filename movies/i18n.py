def get_lang(session: dict[str, Any]) -> str:
    """Return active language code e.g. 'PL', 'EN', 'DE', 'ES', 'FR', 'IT'."""
    return session.get("lang", "PL")


def set_lang(session: dict[str, Any], lang_code: str) -> str:
    code = lang_code.upper().strip()
    if code not in TRANSLATIONS:
        code = "PL"
    session["lang"] = code
    return code


def t(key: str, lang: str = "PL") -> str:
    """Translate key to specified language with fallback to PL."""
    code = lang.upper().strip()
    translations = TRANSLATIONS.get(code, TRANSLATIONS["PL"])
    return translations.get(key, TRANSLATIONS["PL"].get(key, key))
